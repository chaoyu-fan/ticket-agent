export function canTransition(from: RunState, to: RunState): boolean {
  // Same-state events are used for immutable observations (for example, a
  // verified visible price snapshot) and are intentionally idempotent.
  return from === to || transitions[from].includes(to);
}

export function transition(from: RunState, to: RunState): RunState {
  if (!canTransition(from, to)) throw new Error(`INVALID_TRANSITION:${from}->${to}`);
  return to;
}

export function isTerminal(state: RunState): boolean {
  return state === "SUCCESS" || state === "FAILED";
}
